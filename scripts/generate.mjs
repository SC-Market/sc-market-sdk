#!/usr/bin/env node
/**
 * Regenerate the typed client from the live SC Market specs.
 *
 *   npm run generate              fetch the live specs, update openapi/, regenerate
 *   npm run generate -- --offline regenerate from the snapshots in openapi/
 *   npm run generate -- --check   exit 1 if the live specs differ from openapi/ (writes nothing)
 *
 * Sources:
 *   - Public API v1: https://api.sc-market.space/api/public/v1/openapi.json
 *   - Price feed item documents: the PriceOracleItem schema of the site API
 *     spec (https://api.sc-market.space/api/v2/openapi.json), which describes
 *     the same document /api/public/prices/{slug}.json serves. The feed's
 *     index has no schema in any spec: it is hand-typed in src/prices.ts.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { pyOperations, pySchemas, reachableSchemas, tsOperations, tsSchemas } from "./lib/codegen.mjs"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const API = process.env.SC_MARKET_API_ORIGIN ?? "https://api.sc-market.space"
const SOURCES = {
  publicV1: { url: `${API}/api/public/v1/openapi.json`, file: "openapi/public-v1.json" },
  prices: { url: `${API}/api/v2/openapi.json`, file: "openapi/prices-v2-subset.json", roots: ["PriceOracleItem"] },
}

const args = new Set(process.argv.slice(2))
const offline = args.has("--offline")
const check = args.has("--check")

const read = (rel) => JSON.parse(readFileSync(join(ROOT, rel), "utf8"))
const write = (rel, text) => {
  mkdirSync(dirname(join(ROOT, rel)), { recursive: true })
  writeFileSync(join(ROOT, rel), text)
  console.log(`  wrote ${rel}`)
}
const stable = (v) => `${JSON.stringify(v, null, 2)}\n`

async function fetchJson(url) {
  const res = await fetch(url, { headers: { Accept: "application/json" } })
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return res.json()
}

/** Only the price document's schemas, so the snapshot stays small and focused. */
function pricesSubset(v2) {
  const schemas = reachableSchemas(v2.components.schemas, SOURCES.prices.roots)
  return {
    openapi: v2.openapi,
    info: { title: "SC Market price feed documents (subset of the site API spec)", version: v2.info.version, "x-source": SOURCES.prices.url },
    paths: {},
    components: { schemas },
  }
}

async function load() {
  if (offline) return { publicV1: read(SOURCES.publicV1.file), prices: read(SOURCES.prices.file) }
  console.log(`Fetching ${SOURCES.publicV1.url}`)
  const publicV1 = await fetchJson(SOURCES.publicV1.url)
  console.log(`Fetching ${SOURCES.prices.url}`)
  const prices = pricesSubset(await fetchJson(SOURCES.prices.url))
  return { publicV1, prices }
}

const specs = await load()

if (check) {
  let changed = false
  for (const key of Object.keys(SOURCES)) {
    const before = readFileSync(join(ROOT, SOURCES[key].file), "utf8")
    if (before !== stable(specs[key])) {
      console.log(`changed: ${SOURCES[key].file}`)
      changed = true
    }
  }
  console.log(changed ? "The live API changed: run `npm run generate`." : "Up to date.")
  process.exit(changed ? 1 : 0)
}

const v1 = specs.publicV1
const header = (lang, source) =>
  lang === "ts"
    ? `// Generated by scripts/generate.mjs from ${source}. Do not edit: run \`npm run generate\`.\n`
    : `# Generated by scripts/generate.mjs from ${source}. Do not edit: run \`npm run generate\`.\n`
const v1Source = `openapi/public-v1.json (${v1.info.title} ${v1.info.version})`

if (!offline) {
  write(SOURCES.publicV1.file, stable(v1))
  write(SOURCES.prices.file, stable(specs.prices))
}
write("src/generated/types.ts", tsSchemas(v1.components.schemas, header("ts", v1Source)))
write(
  "src/generated/client.ts",
  tsOperations(v1, { className: "GeneratedScMarketClient", baseImport: "../http.js", header: header("ts", v1Source) }),
)
write("src/generated/prices.ts", tsSchemas(specs.prices.components.schemas, header("ts", "openapi/prices-v2-subset.json")))
write("python/src/sc_market_sdk/_types.py", pySchemas(v1.components.schemas, header("py", v1Source)))
write("python/src/sc_market_sdk/_operations.py", pyOperations(v1, { className: "GeneratedScMarketClient", header: header("py", v1Source) }))
write("python/src/sc_market_sdk/_prices_types.py", pySchemas(specs.prices.components.schemas, header("py", "openapi/prices-v2-subset.json")))
console.log("Done. Run `npm run build && npm test` and `cd python && python3 -m unittest` next.")
